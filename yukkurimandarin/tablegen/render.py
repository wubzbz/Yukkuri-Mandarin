def syllables() -> tuple[str, ...]:
    """返回全部合法音节（不含声调）。

    Returns:
        顺序稳定的音节元组，可直接用于生成整张音节表。
    """
    return tuple(_SYLLABLES)


def render_hiragana(yinjie: str, tone: str, *, without_accent: bool = False) -> str:
    """按全局规则生成一个音节的假名拟音。

    Args:
        yinjie: 音节（不含声调）。
        tone: 三位声调序列，字符取自 0–5，中间位不能是 0。
        without_accent: 是否去掉音声记号。

    Returns:
        对应的假名拟音；未知音节返回空串。

    Raises:
        ValueError: yinjie 不是字符串，或 tone 不是合法的三位声调序列。
    """
    if not isinstance(yinjie, str):
        raise ValueError("参数类型错误！必须是字符串。")
    gana = _SYLLABLES.get(yinjie)
    if not gana:
        return ""
    if without_accent:
        return f"{gana[0]}{gana[1]}"
    if not isinstance(tone, str) or len(tone) != 3:
        raise ValueError(f"声调必须是3位数字组成的字符串: {tone}.")
    last_tone, this_tone, next_tone = tone
    if (
        last_tone not in "012345"
        or this_tone not in "12345"
        or next_tone not in "012345"
    ):
        raise ValueError(f"声调格式错误: {tone}.")
    return _apply_accent(gana, last_tone, this_tone, next_tone)


def _apply_accent(
    gana: tuple[str, str], last_tone: str, this_tone: str, next_tone: str
) -> str:
    """根据前、本、后三字的声调给假名加上音声记号。"""
    first, second = gana
    if this_tone in "15":
        if last_tone == "0":
            return f"/っ{first}{second}"
        return f"{first}{second}"
    if this_tone == "2":
        return f"/{first}{second}"
    if this_tone == "3":
        if last_tone == "4":
            if next_tone in "03":
                return f"{first}{second}"
            return f"{first}/{second}"
        if next_tone == "3":
            return f"'{first}{second}"
        return f"'{first}/{second}"
    if next_tone in "023":
        return f"{first}'{second}"
    if last_tone == "0":
        return f"{first}'/{second}"
    return f"{first}/{second}"
